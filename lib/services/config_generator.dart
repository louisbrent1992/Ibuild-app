/// Writes a codemagic.yaml for a Flutter app, following the structure of
/// Codemagic's own Flutter quick-start guide.
library;

enum Distribution {
  testFlight('TestFlight'),
  appStore('App Store'),
  adHoc('Ad Hoc');

  const Distribution(this.label);
  final String label;
}

class ConfigOptions {
  const ConfigOptions({
    this.ios = true,
    this.android = false,
    this.distribution = Distribution.testFlight,
    this.bundleId = 'com.example.app',
    this.runTests = true,
    this.integrationName = 'iBuild',
    this.betaGroup = 'App testers',
  });

  final bool ios;
  final bool android;
  final Distribution distribution;
  final String bundleId;
  final bool runTests;

  /// Name of the App Store Connect API key integration in Codemagic.
  final String integrationName;
  final String betaGroup;

  ConfigOptions copyWith({
    bool? ios,
    bool? android,
    Distribution? distribution,
    String? bundleId,
    bool? runTests,
    String? integrationName,
    String? betaGroup,
  }) =>
      ConfigOptions(
        ios: ios ?? this.ios,
        android: android ?? this.android,
        distribution: distribution ?? this.distribution,
        bundleId: bundleId ?? this.bundleId,
        runTests: runTests ?? this.runTests,
        integrationName: integrationName ?? this.integrationName,
        betaGroup: betaGroup ?? this.betaGroup,
      );
}

String iosWorkflowKey(Distribution distribution) => switch (distribution) {
      Distribution.testFlight => 'ios-testflight',
      Distribution.appStore => 'ios-app-store',
      Distribution.adHoc => 'ios-ad-hoc',
    };

const androidWorkflowKey = 'android-release';

String generateCodemagicYaml(ConfigOptions options) {
  final out = StringBuffer()
    ..writeln('# Generated by iBuild. Commit this file to the root of your repository.')
    ..writeln('workflows:');
  if (options.ios) _writeIos(out, options);
  if (options.android) _writeAndroid(out, options);
  return out.toString();
}

String _quote(String value) {
  final escaped = value.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
  return '"$escaped"';
}

void _script(StringBuffer out, String name, List<String> lines) {
  out
    ..writeln('      - name: $name')
    ..writeln('        script: |');
  for (final line in lines) {
    out.writeln('          $line');
  }
}

void _writeIos(StringBuffer out, ConfigOptions o) {
  final toStore = o.distribution != Distribution.adHoc;
  out
    ..writeln('  ${iosWorkflowKey(o.distribution)}:')
    ..writeln('    name: iOS ${o.distribution.label}')
    ..writeln('    max_build_duration: 60')
    ..writeln('    instance_type: mac_mini_m2');
  if (toStore) {
    out
      ..writeln('    integrations:')
      ..writeln('      app_store_connect: ${_quote(o.integrationName)}');
  }
  out
    ..writeln('    environment:')
    ..writeln('      flutter: stable')
    ..writeln('      xcode: latest')
    ..writeln('      cocoapods: default')
    ..writeln('      ios_signing:')
    ..writeln('        distribution_type: ${toStore ? 'app_store' : 'ad_hoc'}')
    ..writeln('        bundle_identifier: ${_quote(o.bundleId)}');
  if (toStore) {
    out
      ..writeln('      vars:')
      ..writeln('        # Your app\'s numeric Apple ID, from App Store Connect > App Information.')
      ..writeln('        APP_STORE_APPLE_ID: "0000000000"');
  }
  out.writeln('    scripts:');
  _script(out, 'Set up code signing settings on Xcode project',
      ['xcode-project use-profiles']);
  _script(out, 'Get Flutter packages', ['flutter pub get']);
  _script(out, 'Install pods', [r'find . -name "Podfile" -execdir pod install \;']);
  if (o.runTests) _script(out, 'Flutter tests', ['flutter test']);
  if (toStore) {
    _script(out, 'Flutter build ipa', [
      r'NEXT_BUILD=$(($(app-store-connect get-latest-testflight-build-number "$APP_STORE_APPLE_ID") + 1))',
      r'flutter build ipa --release \',
      r'  --build-number=$NEXT_BUILD \',
      '  --export-options-plist=/Users/builder/export_options.plist',
    ]);
  } else {
    _script(out, 'Flutter build ipa', [
      r'flutter build ipa --release \',
      r'  --build-number=$BUILD_NUMBER \',
      '  --export-options-plist=/Users/builder/export_options.plist',
    ]);
  }
  out
    ..writeln('    artifacts:')
    ..writeln('      - build/ios/ipa/*.ipa')
    ..writeln('      - /tmp/xcodebuild_logs/*.log');
  if (toStore) {
    out
      ..writeln('    publishing:')
      ..writeln('      app_store_connect:')
      ..writeln('        auth: integration')
      ..writeln('        submit_to_testflight: true');
    final group = o.betaGroup.trim();
    if (group.isNotEmpty) {
      out
        ..writeln('        beta_groups:')
        ..writeln('          - ${_quote(group)}');
    }
    if (o.distribution == Distribution.appStore) {
      out.writeln('        submit_to_app_store: true');
    }
  }
}

/// Android release: a signed App Bundle uploaded to Google Play as a draft
/// on the production track, so nothing reaches users until it is rolled out
/// by hand in Play Console.
///
/// Secrets come from two Codemagic variable groups rather than the uploaded
/// keystore identity, so they can be created through the API:
///   android_signing  CM_KEYSTORE (base64), CM_KEYSTORE_PASSWORD,
///                    CM_KEY_ALIAS, CM_KEY_PASSWORD
///   play_publishing  GCLOUD_SERVICE_ACCOUNT_CREDENTIALS (service account JSON)
void _writeAndroid(StringBuffer out, ConfigOptions o) {
  out
    ..writeln('  $androidWorkflowKey:')
    ..writeln('    name: Android release')
    ..writeln('    max_build_duration: 60')
    ..writeln('    # Linux machines need a paid Codemagic plan; the Mac builds Android too.')
    ..writeln('    instance_type: mac_mini_m2')
    ..writeln('    environment:')
    ..writeln('      flutter: stable')
    ..writeln('      groups:')
    ..writeln('        - android_signing')
    ..writeln('        - play_publishing')
    ..writeln('      vars:')
    ..writeln('        PACKAGE_NAME: ${_quote(o.bundleId)}')
    ..writeln('    scripts:');
  _script(out, 'Set up local.properties', [
    r'echo "flutter.sdk=$HOME/programs/flutter" > "$CM_BUILD_DIR/android/local.properties"',
  ]);
  _script(out, 'Set up signing', [
    '# android/app/build.gradle(.kts) signs release builds from key.properties.',
    r'echo "$CM_KEYSTORE" | base64 --decode > /tmp/upload-keystore.jks',
    r'cat > "$CM_BUILD_DIR/android/key.properties" <<EOF',
    'storeFile=/tmp/upload-keystore.jks',
    r'storePassword=$CM_KEYSTORE_PASSWORD',
    r'keyAlias=$CM_KEY_ALIAS',
    r'keyPassword=$CM_KEY_PASSWORD',
    'EOF',
  ]);
  _script(out, 'Get Flutter packages', ['flutter pub get']);
  if (o.runTests) _script(out, 'Flutter tests', ['flutter test']);
  _script(out, 'Build Android App Bundle', [
    r'LATEST=$(google-play get-latest-build-number --package-name "$PACKAGE_NAME" || echo 0)',
    r'flutter build appbundle --release --build-number=$((LATEST + 1))',
  ]);
  out
    ..writeln('    artifacts:')
    ..writeln('      - build/**/outputs/**/*.aab')
    ..writeln('    publishing:')
    ..writeln('      google_play:')
    ..writeln(r'        credentials: $GCLOUD_SERVICE_ACCOUNT_CREDENTIALS')
    ..writeln('        track: production')
    ..writeln('        submit_as_draft: true');
}
